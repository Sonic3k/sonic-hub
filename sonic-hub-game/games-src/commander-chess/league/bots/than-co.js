          if (legal === 0) v = search(ply + 1, nd, alpha, beta);
          else {
            v = search(ply + 1, nd - red, alpha, alpha + 1);
            if (v > alpha && red > 0) v = search(ply + 1, nd, alpha, alpha + 1);
            if (v > alpha && v < beta) v = search(ply + 1, nd, alpha, beta);
          }
