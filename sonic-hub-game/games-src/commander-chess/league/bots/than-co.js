/* the points from which a plane would threaten what side X has on point c, and whether a plane of the other side
   can reach one of them now and not be taken there: returns holes | hot << 8 */
const E_hole = new Uint8Array(2 * NSQ);                        // [X * NSQ + point]: a plane landing here would threaten X's Commander
function airHoles(ply, X, c, mark) {
  const o = ply * STRIDE, mo = adMask(ply, X), Y = 1 - X, np = E_np[Y];
  const T = ADM[mo + c], iX = X * NSQ, moY = adMask(ply, Y);
  let holes = 0, hot = 0;
  for (let d = 0; d < 8; d++) {
    const rb = (c * 8 + d) * 12, len = RAYL[c * 8 + d], lim = len < 4 ? len : 4;
    for (let i = 0; i < lim; i++) {
      const sq = RAYB[rb + i];
      if (B[o + sq] !== NONE || ADM[mo + sq] || TERR[sq] === T_WATER) continue;
      let ic = false;
      for (let j = i - 1; j >= 0; j--) { const u = ADM[mo + RAYB[rb + j]]; if (u & ~T) { ic = true; break; } if (u & T) break; }
      if (ic) continue;
      holes++; if (mark) E_hole[iX + sq] = 1;
      if (hot || (E_INF[iX + sq] & 63)) continue;
      /* can one of their planes land here, and can none of ours take it when it has? */
      let can = false;
      for (let x = 0; x < np && !can; x++) {
        const P = B[o + O_AT + E_planes[Y * 4 + x]], li = LINE[P * NSQ + sq];
        if (li !== 255 && (li & 15) < 4 && airOut(mo, (P * 8 + (li >> 4)) * 12, li & 15) === 0) can = true;
      }
      if (!can) continue;
      for (let x = 0; x < E_nap[X] && can; x++) {
        const pl = E_allpl[X * 4 + x], P = B[o + O_AT + pl], li = LINE[P * NSQ + sq];
        if (li !== 255 && (li & 15) < 4 + B[o + O_HERO + pl] && (B[o + O_HERO + pl] || airOut(moY, (P * 8 + (li >> 4)) * 12, li & 15) === 0)) can = false;
      }
      if (can) hot = 1;
    }
  }
  return holes | (hot << 8);
}
