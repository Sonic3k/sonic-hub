#!/usr/bin/env python3
"""Writes ../music.js: the list the car's screen falls back on where the page cannot reach Sonic Hub (a preview shut in
a frame): the songs of one of his lists that have their sound in the hub, as [key, title, artist, record, seconds].
usage: python3 music.py [list key]      (reads https://angels-islands-api-production.up.railway.app/api/music/playlists/<key>)"""
import sys, json, os, urllib.request, urllib.parse, datetime
API = 'https://angels-islands-api-production.up.railway.app/api'
key = sys.argv[1] if len(sys.argv) > 1 else 'spotify-sonic3k-driving-1'
d = json.load(urllib.request.urlopen(f'{API}/music/playlists/{urllib.parse.quote(key, safe="")}', timeout=60))
rows = []
for e in d['entries']:
    t = e.get('track')
    if not t or not t.get('hasAudio'): continue
    rows.append([t['key'], t['title'] + (f" ({t['version']})" if t.get('version') else ''), (t.get('artist') or {}).get('name', ''), (t.get('album') or {}).get('title', ''), t.get('durationSec') or 0])
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'music.js')
with open(out, 'w') as f:
    f.write(f'/* Generated by data/music.py on {datetime.date.today().isoformat()} from Sonic Hub\'s music library — do not edit by hand.\n   "{d["title"]}": the {len(rows)} songs of the list that have their sound in the hub. [key, title, artist, record, seconds] */\n')
    f.write('export default ' + json.dumps({'key': d['key'], 'title': d['title'], 'tracks': rows}, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(rows), 'songs →', out)
