"""Turns an OpenStreetMap extract (the API's /map?bbox=-118.4030,33.9170,-118.3860,33.9300, saved as osm.xml) into
osm.js: the streets, buildings and the Green Line around the hotel, in the place's metres (x east, z south, origin at
33.92290 N, 118.39500 W). Data (c) OpenStreetMap contributors, ODbL. usage: python3 osm2js.py osm.xml ../osm.js

What it leaves out on purpose: the hotel and the Ralphs (built by hand in hotel.js and town.js), and buildings put
up after 2015 (the place is September 2015)."""
import sys, math, json, xml.etree.ElementTree as ET
LAT0, LON0 = 33.92290, -118.39500
KX = math.cos(math.radians(LAT0)) * 111320.0; KZ = 110574.0
X0, X1, Z0, Z1 = -280, 780, -270, 250
HAND = {'233384215', '233386980', '233386985', '51765450', '233384216', '233384214'}   # hotel x3, Ralphs, the two pads
LATER = {'1064298459', '926102517', '1058433610', '769735781', '1461989869', '1461989872', '1070474903', '1070474904'}  # Chick-fil-A, Cambria, AC, Hampton, W XYZ, 2 later retail

t = ET.parse(sys.argv[1]).getroot()
nodes = {n.get('id'): (float(n.get('lat')), float(n.get('lon'))) for n in t.findall('node')}
def P(nid):
    la, lo = nodes[nid]; return (round((lo - LON0) * KX, 1), round(-(la - LAT0) * KZ, 1))
def simplify(pts, eps=0.35):
    if len(pts) < 4: return pts
    def rdp(a):
        if len(a) < 3: return a
        (x0, z0), (x1, z1) = a[0], a[-1]; dx, dz = x1 - x0, z1 - z0; L = math.hypot(dx, dz) or 1e-9
        best, bi = 0, 0
        for i in range(1, len(a) - 1):
            d = abs((a[i][0] - x0) * dz - (a[i][1] - z0) * dx) / L
            if d > best: best, bi = d, i
        if best > eps: return rdp(a[:bi + 1])[:-1] + rdp(a[bi:])
        return [a[0], a[-1]]
    closed = pts[0] == pts[-1]
    out = rdp(pts)
    return out
def inside(pts):
    cx = sum(p[0] for p in pts) / len(pts); cz = sum(p[1] for p in pts) / len(pts)
    return X0 < cx < X1 and Z0 < cz < Z1
def flat(pts): return [v for p in pts for v in p]

H_DEFAULT = {'house': 5.5, 'residential': 6.5, 'apartments': 8.5, 'garage': 3.0, 'garages': 3.0, 'roof': 4.5, 'retail': 6.0,
             'commercial': 9.0, 'industrial': 8.0, 'warehouse': 9.0, 'hotel': 12.0, 'office': 15.0, 'yes': 7.0}
buildings, roads, service, rail, platform, parking, green, pois = [], [], [], [], [], [], [], []
for w in t.findall('way'):
    wid = w.get('id'); tg = {g.get('k'): g.get('v') for g in w.findall('tag')}
    pts = [P(n.get('ref')) for n in w.findall('nd') if n.get('ref') in nodes]
    if len(pts) < 2 or not inside(pts): continue
    if 'building' in tg and wid not in HAND and wid not in LATER:
        sd = tg.get('start_date', '')
        if sd[:4].isdigit() and int(sd[:4]) > 2015: continue
        h = float(tg['height']) if tg.get('height', '').replace('.', '').isdigit() else (float(tg['building:levels']) * 3.3 if tg.get('building:levels', '').isdigit() else H_DEFAULT.get(tg['building'], 7.0))
        p = simplify(pts[:-1] if pts[0] == pts[-1] else pts)
        if len(p) >= 3: buildings.append([wid, round(h, 1), tg['building'], tg.get('name', ''), flat(p)])
    elif tg.get('highway') in ('primary', 'secondary', 'tertiary', 'residential', 'unclassified', 'tertiary_link', 'primary_link'):
        lanes = int(tg.get('lanes', '2').split(';')[0]) if tg.get('lanes', '2').split(';')[0].isdigit() else 2
        roads.append([tg.get('name', ''), tg['highway'], lanes, 1 if tg.get('oneway') == 'yes' else 0, flat(simplify(pts, 0.25))])
    elif tg.get('highway') == 'service' and tg.get('service') != 'drive-through':
        service.append([tg.get('service', ''), flat(simplify(pts, 0.3))])
    elif tg.get('railway') == 'light_rail':
        rail.append([1 if tg.get('bridge') == 'yes' else 0, flat(simplify(pts, 0.15))])
    elif tg.get('railway') == 'platform':
        platform.append(flat(pts))
    elif tg.get('amenity') == 'parking' and 'building' not in tg:
        parking.append(flat(simplify(pts)))
    elif tg.get('landuse') == 'grass' or tg.get('leisure') in ('park', 'pitch'):
        green.append(flat(simplify(pts)))
for n in t.findall('node'):
    tg = {g.get('k'): g.get('v') for g in n.findall('tag')}
    if tg.get('highway') in ('traffic_signals', 'bus_stop', 'street_lamp') or tg.get('railway') in ('station', 'stop'):
        x, z = P(n.get('id'))
        if X0 < x < X1 and Z0 < z < Z1: pois.append([tg.get('highway') or tg.get('railway'), tg.get('name', ''), x, z])

def js(name, v): return f'export const {name} = {json.dumps(v, separators=(",", ":"))};\n'
with open(sys.argv[2], 'w') as f:
    f.write('/* Generated by data/osm2js.py from OpenStreetMap (c) OpenStreetMap contributors, ODbL — do not edit by hand.\n'
            '   Metres: x east, z south, origin 33.92290 N 118.39500 W. Buildings: [osm id, height, kind, name, [x,z,…]].\n'
            '   Roads: [name, class, lanes, oneway, [x,z,…]] (centre lines). Service: [kind, [x,z,…]]. Rail: [bridge, [x,z,…]]. */\n')
    f.write(js('BUILDINGS', buildings)); f.write(js('ROADS', roads)); f.write(js('SERVICE', service)); f.write(js('RAIL', rail))
    f.write(js('PLATFORM', platform)); f.write(js('PARKING', parking)); f.write(js('GREEN', green)); f.write(js('POINTS', pois))
print(len(buildings), 'buildings', len(roads), 'roads', len(service), 'service', len(rail), 'rail', len(parking), 'parking', len(green), 'green', len(pois), 'points')
