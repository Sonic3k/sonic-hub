"""The game shelf: series, games, when he played them, and what ties them to his memories.

Every play carries its evidence (a save file's date, a screenshot, a photo, a line in his 2004 lists), so a reader can
see why the hub says he played a game then. Media and memories are referred to by the first 8 characters of their id,
resolved through ids.json by push_to_hub.py. Notes on games hold his own words only.
"""
from urllib.parse import quote_plus

PAGES = "https://sonic-hub-pages-production.up.railway.app"


def play(start, device=None, end=None, precision=None, approx=None, via=None, version=None, evidence=None, note=None):
    return {k: v for k, v in dict(start=start, device=device, end=end, precision=precision, approx=approx, via=via,
                                  version=version, evidence=evidence, note=note).items() if v is not None}


def wiki(path):
    return {"kind": "WIKI", "title": "Wikipedia", "url": "https://en.wikipedia.org/wiki/" + path}


def yt(title, kind="LONGPLAY", note=None):
    """A video he saved in 10/2015, found again on YouTube by its exact title."""
    return {"kind": kind, "title": title, "url": "https://www.youtube.com/results?search_query=" + quote_plus(title),
            "note": note}


def page(slug, title="Chơi trên Sonic Hub Pages"):
    return {"kind": "PLAY", "title": title, "url": f"{PAGES}/{slug}"}


def pic(prefix, role="PHOTO", label=None):
    return {"m": prefix, "role": role, "label": label}


